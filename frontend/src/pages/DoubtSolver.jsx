import { useEffect, useRef, useState } from "react";
import axios from "axios";
import ReactMarkdown from "react-markdown";
import Sidebar from "../components/Sidebar";
import Topbar from "../components/Topbar";
import "../styles/doubtSolver.css";

const SUGGESTIONS = [
  { label: "What is normalization in DBMS?", question: "What is normalization in DBMS?" },
  { label: "Explain deadlock in OS", question: "Explain deadlock in operating system." },
  { label: "Explain OSI Model", question: "Explain OSI model layers." },
  { label: "What is inheritance in Java?", question: "What is inheritance in Java?" }
];

const TIPS = [
  "Mention the subject or topic.",
  "Ask one concept at a time.",
  "Ask for examples if needed.",
  "Use clear academic questions."
];

const SOURCE_BADGES = {
  history: { className: "historyAnswerBadge", label: "⚡ Answer reused from your doubt history" },
  gemini: { className: "geminiAnswerBadge", label: "✨ Generated by StudyGenie AI" }
};

const authConfig = () => ({
  headers: { Authorization: `Bearer ${localStorage.getItem("token")}` }
});

const newId = () => `${Date.now()}-${Math.random()}`;

function DoubtSolver() {
  const [question, setQuestion] = useState("");
  const [messages, setMessages] = useState([]);
  const [doubtHistory, setDoubtHistory] = useState([]);
  const [loading, setLoading] = useState(false);
  const [quotaBlocked, setQuotaBlocked] = useState(false);
  const [showAllHistory, setShowAllHistory] = useState(false);
  const messagesEndRef = useRef(null);

  const addMessage = (message) =>
    setMessages((prev) => [...prev, { id: newId(), ...message }]);

  const loadHistory = async () => {
    if (!localStorage.getItem("token")) return;
    try {
      const { data } = await axios.get("/api/doubts", authConfig());
      if (Array.isArray(data)) setDoubtHistory(data);
    } catch (error) {
      console.error("Fetch Doubt History Error:", error.response?.data?.message || error.message);
    }
  };

  useEffect(() => {
    loadHistory();
  }, []);

  useEffect(() => {
    messagesEndRef.current?.scrollIntoView({ behavior: "smooth" });
  }, [messages, loading]);

  const handleAskDoubt = async () => {
    if (loading || quotaBlocked) return;
    const text = question.trim();
    if (!text) return alert("Please enter your doubt.");
    if (!localStorage.getItem("token")) return alert("Please login first.");

    addMessage({ role: "user", text });
    setQuestion("");
    setLoading(true);

    try {
      const { data } = await axios.post("/api/doubts/ask", { question: text }, authConfig());
      addMessage({ role: "assistant", text: data.answer, source: data.source });
      loadHistory();
    } catch (error) {
      const data = error.response?.data;
      if (data?.code === "AI_QUOTA_EXHAUSTED") setQuotaBlocked(true);
      console.error("Ask Doubt Error:", error.response?.status || 0, data?.message || error.message);
      addMessage({
        role: "assistant",
        text: data?.message || "Sorry, I could not solve this doubt right now."
      });
    } finally {
      setLoading(false);
    }
  };

  const handleKeyDown = (e) => {
    if (e.key === "Enter" && !e.shiftKey) {
      e.preventDefault();
      handleAskDoubt();
    }
  };

  const handleNewChat = () => {
    setMessages([]);
    setQuestion("");
  };

  const handleOpenHistory = (doubt) => {
    setMessages([
      { id: `${doubt._id}-question`, role: "user", text: doubt.question },
      { id: `${doubt._id}-answer`, role: "assistant", text: doubt.answer, source: "history" }
    ]);
    window.scrollTo({ top: 0, behavior: "smooth" });
  };

  const handleDeleteDoubt = async (doubt) => {
    if (!window.confirm(`Delete "${doubt.question}"?`)) return;
    try {
      await axios.delete(`/api/doubts/${doubt._id}`, authConfig());
      setDoubtHistory((prev) => prev.filter((d) => d._id !== doubt._id));
    } catch (error) {
      alert(error.response?.data?.message || "Failed to delete doubt");
    }
  };

  const visibleHistory = showAllHistory ? doubtHistory : doubtHistory.slice(0, 4);

  return (
    <div className="dashboardLayout">
      <Sidebar />

      <main className="dashboardMain">
        <Topbar />

        <section className="doubtHeader">
          <div>
            <h1>AI Doubt Solver</h1>
            <p>Ask academic questions and get clear AI-powered explanations.</p>
          </div>
          <button className="newChatBtn" onClick={handleNewChat}>＋ New Chat </button>
        </section>

        <section className="doubtMainGrid">
          {/* CHAT */}
          <div className="doubtChatCard">
            <div className="chatHeader">
              <div className="chatBotAvatar">🤖</div>
              <div>
                <h3>StudyGenie AI</h3>
                <p>Academic Doubt Assistant</p>
              </div>
              <span className="onlineBadge">● Online</span>
            </div>

            <div className="chatMessages">
              {messages.length === 0 && (
                <div className="chatWelcome">
                  <div className="welcomeRobot">🤖</div>
                  <h2>How can I help you today?</h2>
                  <p>
                    Ask any B.Sc. IT academic question and StudyGenie will explain it in
                    simple language.
                  </p>
                  <div className="suggestedQuestions">
                    {SUGGESTIONS.map((s) => (
                      <button key={s.label} onClick={() => setQuestion(s.question)}>
                        {s.label}
                      </button>
                    ))}
                  </div>
                </div>
              )}

              {messages.map((message) => {
                const isUser = message.role === "user";
                const badge = !isUser && SOURCE_BADGES[message.source];
                return (
                  <div
                    key={message.id}
                    className={`messageRow ${isUser ? "userMessageRow" : "aiMessageRow"}`}
                  >
                    {!isUser && <div className="messageAvatar">🤖</div>}
                    <div className={`messageBubble ${isUser ? "userBubble" : "aiBubble"}`}>
                      {isUser ? <p>{message.text}</p> : <ReactMarkdown>{message.text}</ReactMarkdown>}
                      {badge && <div className={badge.className}>{badge.label}</div>}
                    </div>
                    {isUser && <div className="messageAvatar userAvatar">👤</div>}
                  </div>
                );
              })}

              {loading && (
                <div className="messageRow aiMessageRow">
                  <div className="messageAvatar">🤖</div>
                  <div className="messageBubble aiBubble typingBubble">
                    <span></span>
                    <span></span>
                    <span></span>
                  </div>
                </div>
              )}

              <div ref={messagesEndRef}></div>
            </div>

            <div className="chatInputArea">
              <textarea
                placeholder="Ask your academic doubt..."
                value={question}
                onChange={(e) => setQuestion(e.target.value)}
                onKeyDown={handleKeyDown}
                rows="2"
                disabled={loading || quotaBlocked}
              />
              <button
                className="sendDoubtBtn"
                onClick={handleAskDoubt}
                disabled={loading || quotaBlocked || !question.trim()}
              >
                {loading ? "..." : quotaBlocked ? "—" : "➤"}
              </button>
            </div>

            <div className="chatInputHint">
              {quotaBlocked
                ? "Daily AI quota reached. Reload this page after the quota resets."
                : "Press Enter to send • Shift + Enter for new line"}
            </div>
          </div>

          {/* RIGHT SIDE */}
          <aside className="doubtRightPanel">
            <div className="doubtSideCard">
              <div className="doubtSideHeader">
                <h3>🕘 Doubt History</h3>
                {doubtHistory.length > 4 && (
                  <button onClick={() => setShowAllHistory(!showAllHistory)}>
                    {showAllHistory ? "Show Less" : "View All"}
                  </button>
                )}
              </div>

              {visibleHistory.length > 0 ? (
                visibleHistory.map((doubt) => (
                  <HistoryItem
                    key={doubt._id}
                    doubt={doubt}
                    onOpen={handleOpenHistory}
                    onDelete={handleDeleteDoubt}
                  />
                ))
              ) : (
                <div className="noDoubtHistory">No doubts asked yet.</div>
              )}
            </div>

            <div className="doubtSideCard autoFaqCard">
              <div className="autoFaqIcon">⚡</div>
              <h3>Auto-FAQ</h3>
              <p>StudyGenie checks your previous doubts before contacting AI.</p>
              <div className="autoFaqFlow">
                <span>Question</span>
                <b>→</b>
                <span>History</span>
                <b>→</b>
                <span>AI</span>
              </div>
            </div>

            <div className="doubtSideCard doubtTips">
              <h3>💡 Ask Better Questions</h3>
              <ul>
                {TIPS.map((tip) => (
                  <li key={tip}>{tip}</li>
                ))}
              </ul>
            </div>
          </aside>
        </section>
      </main>
    </div>
  );
}

function HistoryItem({ doubt, onOpen, onDelete }) {
  return (
    <div className="doubtHistoryItem">
      <div className="doubtHistoryContent" onClick={() => onOpen(doubt)}>
        <div className="historyQuestionIcon">?</div>
        <div className="historyQuestionText">
          <h4>{doubt.question}</h4>
          <span>{new Date(doubt.createdAt).toLocaleDateString()}</span>
        </div>
      </div>
      <button className="deleteDoubtBtn" title="Delete Doubt" onClick={() => onDelete(doubt)}>
        🗑️
      </button>
    </div>
  );
}

export default DoubtSolver;